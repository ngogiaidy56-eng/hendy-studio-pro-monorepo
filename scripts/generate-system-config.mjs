#!/usr/bin/env node
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';

const root = process.cwd();
const result = spawnSync(process.execPath, [resolve(root, 'scripts/validate-system-config.mjs')], { cwd: root, stdio: 'inherit' });
if (result.status !== 0) process.exit(result.status ?? 1);
const config = JSON.parse(await readFile(resolve(root, 'system-config/system.config.json'), 'utf8'));
delete config.$schema;
const outputPath = resolve(root, 'packages/core-utils/src/system-config.generated.ts');
await mkdir(dirname(outputPath), { recursive: true });
const source = `/* AUTO-GENERATED by scripts/generate-system-config.mjs. Do not edit by hand. */\nexport const SYSTEM_CONFIG = ${JSON.stringify(config, null, 2)} as const;\n\nexport type SystemConfig = typeof SYSTEM_CONFIG;\n`;
await writeFile(outputPath, source, 'utf8');
console.log(`Generated ${outputPath.replace(root + '/', '')}`);
